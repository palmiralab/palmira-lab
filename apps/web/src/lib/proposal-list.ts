// Пункты списка КП (состав работ, допущения, исключения) в том виде, в каком их
// показываем. GigaChat иногда сам добавляет "- " в начало пункта — в <li> это
// задвоило бы буллет ("• - текст"), убираем. Пустые пункты выбрасываем: пустой
// итоговый список значит, что раздел в КП не показываем вовсе.
export function listItems(items: string[]): string[] {
  return items.map((item) => item.trim().replace(/^[-•]\s*/, '').trim()).filter(Boolean);
}
