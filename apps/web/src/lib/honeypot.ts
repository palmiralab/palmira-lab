// Приманка для ботов: поле, которого человек не видит и не заполняет, а бот,
// проходящий по всем полям формы, заполняет. Заявку с непустой приманкой сайт
// принимает «с улыбкой» (200), но никуда не передаёт: бот не узнаёт, что его
// раскусили. Название выбрано неочевидным и без «website», который охотно
// подставляют менеджеры паролей и автозаполнение браузера.
export const HONEYPOT_FIELD = 'company_website';

// Значение поля читаем из DOM в момент отправки: поле неуправляемое (человек в
// него не пишет), и протаскивать состояние через четыре компонента ради него
// было бы лишним шумом. Вне браузера (тесты, сервер) поля нет, значит пусто.
export function readHoneypot(): string {
  if (typeof document === 'undefined') return '';
  const field = document.querySelector<HTMLInputElement>(`input[name="${HONEYPOT_FIELD}"]`);
  return field?.value ?? '';
}
